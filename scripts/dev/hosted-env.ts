// Writes an untracked env file for a hosted Supabase project (default: dev) from
// SUPABASE_DEV_PROJECT_REF and SUPABASE_DEV_DB_PASSWORD. Role passwords are
// generated once and kept; nothing secret is printed. Connections go through
// Supavisor: session mode (5432) for bootstrap and migrations, transaction mode
// (6543) for the runtime roles, exactly as the deployed app and worker will use.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const FILE = process.argv.slice(2).find((a) => !a.startsWith("--")) ?? ".env.dev-hosted";
const ref = process.env.SUPABASE_DEV_PROJECT_REF;
const postgresPassword = process.env.SUPABASE_DEV_DB_PASSWORD;
const host = process.env.SUPABASE_POOLER_HOST ?? "aws-0-us-east-1.pooler.supabase.com";
if (!ref || !postgresPassword) throw new Error("SUPABASE_DEV_PROJECT_REF and SUPABASE_DEV_DB_PASSWORD must be set");

const current = new Map<string, string>();
if (existsSync(FILE)) {
  for (const line of readFileSync(FILE, "utf8").split("\n")) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) current.set(m[1], m[2]);
  }
}
// --rotate generates fresh role passwords (apply them with db:bootstrap).
const rotate = process.argv.includes("--rotate");
const unquote = (v?: string) => v?.replace(/^'(.*)'$/, "$1");
const keep = (k: string) => (!rotate && unquote(current.get(k))) || randomBytes(24).toString("hex");
const pw = {
  MIGRATION_OWNER_PASSWORD: keep("MIGRATION_OWNER_PASSWORD"),
  APP_USER_PASSWORD: keep("APP_USER_PASSWORD"),
  WORKER_USER_PASSWORD: keep("WORKER_USER_PASSWORD"),
  ADMIN_USER_PASSWORD: keep("ADMIN_USER_PASSWORD"),
};
const url = (role: string, password: string, port: number) =>
  `postgresql://${role}.${ref}:${encodeURIComponent(password)}@${host}:${port}/postgres?sslmode=require&uselibpqcompat=true`;

const values: Record<string, string> = {
  APP_ENV: "dev",
  ...pw,
  DATABASE_URL_BOOTSTRAP: url("postgres", postgresPassword, 5432),
  DATABASE_URL_MIGRATION: url("migration_owner", pw.MIGRATION_OWNER_PASSWORD, 5432),
  DATABASE_URL_APP: url("app_user", pw.APP_USER_PASSWORD, 6543),
  DATABASE_URL_WORKER: url("worker_user", pw.WORKER_USER_PASSWORD, 6543),
  DATABASE_URL_ADMIN: url("admin_user", pw.ADMIN_USER_PASSWORD, 6543),
};
writeFileSync(
  FILE,
  `# Hosted Supabase dev project ${ref}. Generated by scripts/dev/hosted-env.ts. Untracked; contains secrets.\n` +
    // Single-quoted: URLs contain "&", which an unquoted value turns into shell
    // background jobs (and echoes the secrets) if the file is ever sourced.
    Object.entries(values).map(([k, v]) => `${k}='${v}'`).join("\n") + "\n",
  { mode: 0o600 },
);
console.log(`wrote ${FILE} for project ${ref} via ${host}`);
