// Writes an untracked .env.local for the local Supabase stack. Existing values are
// kept (role passwords are generated once); nothing secret is printed.
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const FILE = ".env.local";
const current = new Map<string, string>();
if (existsSync(FILE)) {
  for (const line of readFileSync(FILE, "utf8").split("\n")) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) current.set(m[1], m[2]);
  }
}

const status = Object.fromEntries(
  execFileSync("supabase", ["status", "-o", "env"], { encoding: "utf8" })
    .split("\n")
    .map((l) => l.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter((m): m is RegExpMatchArray => !!m)
    .map((m) => [m[1], m[2]]),
);

const secret = () => randomBytes(32).toString("base64url");
const keep = (name: string, make: () => string) => current.get(name) || make();
const hookSecret = readFileSync("supabase/.env", "utf8").match(
  /SUPABASE_AUTH_HOOK_SECRET="([^"]+)"/,
)?.[1];
if (!hookSecret)
  throw new Error("supabase/.env is missing SUPABASE_AUTH_HOOK_SECRET");

const pw = {
  MIGRATION_OWNER_PASSWORD: keep("MIGRATION_OWNER_PASSWORD", secret),
  APP_USER_PASSWORD: keep("APP_USER_PASSWORD", secret),
  WORKER_USER_PASSWORD: keep("WORKER_USER_PASSWORD", secret),
  ADMIN_USER_PASSWORD: keep("ADMIN_USER_PASSWORD", secret),
};
const db = (role: string, password: string) =>
  `postgresql://${role}:${password}@127.0.0.1:54322/postgres`;

const values: Record<string, string> = {
  APP_ENV: "local",
  APP_BASE_URL: "http://localhost:3000",
  PUBLIC_SIGNUP_ENABLED: keep("PUBLIC_SIGNUP_ENABLED", () => "false"),
  PUBLIC_SHORT_BASE_URL: "http://localhost:3000",
  DATABASE_URL_BOOTSTRAP: status.DB_URL,
  ...pw,
  DATABASE_URL_MIGRATION: db("migration_owner", pw.MIGRATION_OWNER_PASSWORD),
  DATABASE_URL_APP: db("app_user", pw.APP_USER_PASSWORD),
  DATABASE_URL_WORKER: db("worker_user", pw.WORKER_USER_PASSWORD),
  DATABASE_URL_ADMIN: db("admin_user", pw.ADMIN_USER_PASSWORD),
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: status.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
  SUPABASE_AUTH_HOOK_SECRET: hookSecret,
  SESSION_SIGNING_SECRET: keep("SESSION_SIGNING_SECRET", secret),
  DATA_ENCRYPTION_KEY: keep("DATA_ENCRYPTION_KEY", secret),
  ADMIN_ALLOWED_EMAIL_DOMAIN: keep(
    "ADMIN_ALLOWED_EMAIL_DOMAIN",
    () => "example.test",
  ),
  EMAIL_FROM_ADDRESS: "notifications@example.test",
  SMTP_HOST: "127.0.0.1",
  SMTP_PORT: "54325",
  LOG_LEVEL: "info",
};
for (const [k, v] of current) if (!(k in values)) values[k] = v;

writeFileSync(
  FILE,
  "# Generated by scripts/dev/setup-env.ts for the local Supabase stack. Untracked.\n" +
    Object.entries(values)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n",
  { mode: 0o600 },
);
console.log(`wrote ${FILE} (${Object.keys(values).length} variables)`);
